def test_cli_exclude_newer_package_repeats_keep_each_name_and_last_value() -> None:
    options = parse_cli([
        "--exclude-newer-package",
        "foo=2026-10-01T00:00:00Z",
        "--exclude-newer-package",
        "bar=false",
        "--exclude-newer-package",
        "foo=2026-10-02T00:00:00Z",
    ])

    assert options.exclude_newer_package == {"foo": datetime(2026, 10, 2, tzinfo=UTC), "bar": None}


def test_cli_exclude_newer_package_combines_with_exclude_newer() -> None:
    options = parse_cli(["--exclude-newer", "2026-10-01T00:00:00Z", "--exclude-newer-package", "foo=false"])

    assert (options.exclude_newer, options.exclude_newer_package) == (datetime(2026, 10, 1, tzinfo=UTC), {"foo": None})


