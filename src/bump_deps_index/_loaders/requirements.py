from __future__ import annotations

import os
import re
import shlex
from itertools import accumulate
from pathlib import Path
from typing import TYPE_CHECKING, ClassVar, Final

from typing_extensions import override

from bump_deps_index._lookup import PkgType

from ._base import Entry, Loaded, Loader
from ._lines import replace_requirement_line, split_comment

if TYPE_CHECKING:
    from collections.abc import Iterator, Mapping

# pip's comment pattern: a `#` at the start of a line or after whitespace starts a comment
_COMMENT: Final[re.Pattern[str]] = re.compile(r"(^|\s+)#.*$")


class Requirements(Loader):
    _bases: ClassVar[tuple[str, ...]] = ("requirements", "constraints")

    @property
    @override
    def files(self) -> Iterator[Path]:
        found = {f for f in Path.cwd().iterdir() if f.stem.startswith(self._bases) and f.suffix in {".in", ".txt"}}
        existing_names = {f.name for f in found}

        for filename in found:
            if filename.suffix == ".txt" and filename.with_suffix(".in").name in existing_names:
                continue
            with filename.open("rt", encoding="utf-8") as file_handler:
                for line in file_handler:
                    if line.startswith("# This file was autogenerated by"):
                        break
                else:
                    yield filename

    @override
    def supports(self, filename: Path) -> bool:
        return filename.suffix in {".in", ".txt"} and not (
            filename.suffix == ".txt" and filename.with_suffix(".in").exists()
        )

    @override
    def load(self, filename: Path) -> Loaded:
        lines = filename.read_text(encoding="utf-8").split("\n")
        options = list(self._index_options(filename, set()))
        # pip applies the last `--index-url` and every `--extra-index-url`
        index_url = next((value for name, value in reversed(options) if name == "index"), None)
        extra_index_urls = tuple(value for name, value in options if name == "extra")
        return Loaded(
            entries=[
                Entry(
                    spec=" ".join(segment for _, segment in group),
                    pkg_type=PkgType.PYTHON,
                    index_url=index_url,
                    extra_index_urls=extra_index_urls,
                )
                for group in self._requirement_lines(lines)
            ]
        )

    @staticmethod
    def _index_options(filename: Path, seen: set[Path]) -> Iterator[tuple[str, str]]:
        # pip reads the index options of the files that `-r` or `-c` pulls in, too
        seen.add(filename.resolve())
        try:
            lines = filename.read_text(encoding="utf-8").splitlines()
        except (OSError, UnicodeDecodeError):
            return
        for line in Requirements._logical_lines(lines):
            try:
                words = shlex.split(_COMMENT.sub("", line))
            except ValueError:
                continue
            for name, value in Requirements._options(words):
                if name != "include":
                    yield name, Requirements._expand_env(value)
                elif (included := filename.parent / Requirements._expand_env(value)).resolve() not in seen:
                    yield from Requirements._index_options(included, seen)

    @staticmethod
    def _logical_lines(lines: list[str]) -> Iterator[str]:
        # follow pip's `join_lines`: a comment line ends a `\` continuation, and the parts join without a space
        joined: list[str] = []
        for line in lines:
            if _COMMENT.match(line):
                yield "".join(joined)
                joined = []
            elif line.endswith("\\"):
                joined.append(line.removesuffix("\\"))
            else:
                yield "".join([*joined, line])
                joined = []
        yield "".join(joined)

    @staticmethod
    def _options(words: list[str]) -> Iterator[tuple[str, str]]:
        options: Final[dict[str, str]] = {
            "-i": "index",
            "--index-url": "index",
            "--extra-index-url": "extra",
            "-r": "include",
            "--requirement": "include",
            "-c": "include",
            "--constraint": "include",
        }
        for at, word in enumerate(words):
            name, equals, value = word.partition("=")
            if name in options and equals:
                yield options[name], value
            elif word in options and at + 1 < len(words):
                yield options[word], words[at + 1]
            elif word[:2] in {"-i", "-r", "-c"} and len(word) > len("-i"):
                yield options[word[:2]], word[2:]

    @staticmethod
    def _expand_env(text: str) -> str:
        # pip substitutes `${NAME}` with a non-empty variable, and keeps it as written otherwise
        return re.sub(r"\$\{(?P<name>[A-Z0-9_]+)\}", lambda match: os.environ.get(match["name"]) or match[0], text)

    @staticmethod
    def _requirement_lines(lines: list[str]) -> Iterator[list[tuple[int, str]]]:
        group: list[tuple[int, str]] = []
        for at, line in enumerate(lines):
            # pip drops a comment line inside a `\`-continued requirement
            stripped = "" if line.lstrip().startswith("#") else split_comment(line.strip())[0]
            if segment := stripped.removesuffix("\\").rstrip():
                group.append((at, segment))
            if stripped.endswith("\\"):
                continue
            logical = " ".join(segment for _, segment in group)
            # skip hashed entries; you would need new hashes for a new version
            if logical and not logical.startswith("-") and "--hash" not in logical:
                yield group
            group = []

    @override
    def _update_text(self, text: str, changes: Mapping[str, str], kept: tuple[bool, ...]) -> str:
        lines = text.split("\n")
        for group in self._requirement_lines(lines):
            logical = " ".join(segment for _, segment in group)
            if (new := changes.get(logical, logical)) == logical:
                continue
            # find the edited span to rewrite the physical line holding it in a `\`-continued requirement
            start = self._common_prefix(logical, new)
            shared_suffix = self._common_prefix(logical[start:][::-1], new[start:][::-1])
            offsets = accumulate((len(segment) + 1 for _, segment in group), initial=0)
            at, segment, offset = next(
                (at, segment, offset)
                for (at, segment), offset in zip(group, offsets, strict=False)
                if offset <= start and len(logical) - shared_suffix <= offset + len(segment)
            )
            before, after = segment[: start - offset], segment[len(logical) - shared_suffix - offset :]
            edited = f"{before}{new[start : len(new) - shared_suffix]}{after}"
            lines[at] = replace_requirement_line(lines[at], {segment: edited})
        return "\n".join(lines)

    @staticmethod
    def _common_prefix(left: str, right: str) -> int:
        return next(
            (at for at, (first, second) in enumerate(zip(left, right, strict=False)) if first != second),
            min(len(left), len(right)),
        )


__all__ = [
    "Requirements",
]
